#!/usr/bin/env python3
"""Generate library roots so importing a library exposes all its modules."""
from pathlib import Path
import argparse
import sys

ROOT = Path(__file__).resolve().parent.parent
LIBRARIES = ('MTC', 'Conjectures', 'AnyonAtlas')


def render(library):
    modules = sorted('.'.join(path.relative_to(ROOT).with_suffix('').parts)
                     for path in (ROOT / library).rglob('*.lean'))
    return 'module\n\n/- Generated by `scripts/update_roots.py`. -/\n' + ''.join(
        f'public import {module}\n' for module in modules)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='fail if any root is stale')
    args = parser.parse_args()
    stale = []
    for library in LIBRARIES:
        path = ROOT / f'{library}.lean'
        content = render(library)
        if args.check:
            if not path.exists() or path.read_text(encoding='utf-8') != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(content, encoding='utf-8')
    if stale:
        print(f"Stale roots: {', '.join(stale)}; run python3 scripts/update_roots.py", file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
