#!/usr/bin/env python3
"""Validate conjecture metadata and render a deterministic dashboard."""
from pathlib import Path
import argparse
import re
import sys

ROOT = Path(__file__).resolve().parent.parent
STATUSES = {"open", "proved", "disproved"}
FIELDS = ("Status", "Source", "Declaration")
NAME = re.compile(r"[A-Za-z_][A-Za-z0-9_']*(?:\.[A-Za-z_][A-Za-z0-9_']*)+\Z")


def entries():
    results = []
    seen = set()
    for path in sorted((ROOT / "Conjectures").rglob("*.lean")):
        if path.name == "Seed.lean" and path.parent == ROOT / "Conjectures":
            continue
        rel = path.relative_to(ROOT)
        if len(rel.parts) != 3:
            raise ValueError(f"{rel}: expected Conjectures/<Topic>/<Name>.lean")
        text = path.read_text(encoding="utf-8")
        match = re.search(r"/-!(.*?)\-/", text, re.S)
        if not match:
            raise ValueError(f"{rel}: missing module docstring")
        fields = {}
        for field in FIELDS:
            values = re.findall(rf"(?m)^[ \t]*{field}:[ \t]*(\S[^\r\n]*?)[ \t]*$", match.group(1))
            if len(values) != 1:
                raise ValueError(f"{rel}: expected exactly one nonempty {field} field")
            fields[field] = values[0]
        if fields["Status"] not in STATUSES:
            raise ValueError(f"{rel}: invalid status {fields['Status']!r}")
        decl = fields["Declaration"]
        if not NAME.fullmatch(decl) or not decl.startswith(f"MTC.Conjectures.{rel.parts[1]}."):
            raise ValueError(f"{rel}: invalid declaration name {decl!r}")
        if decl in seen:
            raise ValueError(f"{rel}: duplicate declaration {decl}")
        seen.add(decl)
        results.append((rel, fields))
    return results


def render(items):
    lines = ["# Conjecture status", "", "Generated by `scripts/conjecture_status.py`; do not edit by hand.", "", "| Topic | Declaration | Status | Source |", "| --- | --- | --- | --- |"]
    for path, fields in items:
        source = fields["Source"].replace("|", "\\|")
        lines.append(f"| {path.parts[1]} | [`{fields['Declaration']}`](../{path.as_posix()}) | {fields['Status']} | {source} |")
    if not items:
        lines += ["", "No conjectures have been added yet."]
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the checked-in dashboard is stale")
    args = parser.parse_args()
    try:
        output = render(entries())
        path = ROOT / "docs" / "STATUS.md"
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != output:
                raise ValueError("docs/STATUS.md is stale; run python3 scripts/conjecture_status.py")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(output, encoding="utf-8")
    except (ValueError, OSError) as exc:
        print(exc, file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
